"""Вывод в терминал, который не умеет юникод.

Эмулятор рисует кириллицу — текст ЭВМ и подвал — и служебные знаки:
блок заливки (курсор, УП), «№». Обычный терминал это показывает, а
«жёсткий» (ASCII-локаль, консоль без юникодного шрифта, KOI8-R/cp866 без
псевдографики) — нет: `sys.stdout.write` падает UnicodeEncodeError, и весь
сеанс валится на первом же русском слове.

Здесь вывод приводится к тому, что терминал показать может: знак, который
кодировка не берёт, заменяется на ближайший печатный — кириллица
транслитерируется в латиницу, псевдографика — в ASCII. Работать можно
всегда, пусть и с romanized текстом.
"""

from __future__ import annotations

import sys

# Проба «жёсткости»: кириллица + знаки, которых нет в однобайтовых
# кодировках. Если кодировка терминала хоть что-то из этого не берёт —
# подстраховка включается.
PROBE = "Абвгд█▓№…"


def _can_encode(text: str, encoding: str) -> bool:
    try:
        text.encode(encoding)
    except (UnicodeEncodeError, LookupError, TypeError):
        return False
    return True


def console_encoding(stream=None) -> str:
    """Кодировка терминала по локали (без догадок и без перекодировки)."""
    st = sys.stdout if stream is None else stream
    return (getattr(st, "encoding", None) or "").strip().lower() or "ascii"


def is_hard(encoding: str | None = None) -> bool:
    """«Жёсткий» ли терминал: не берёт юникод и псевдографику."""
    return not _can_encode(PROBE, encoding or console_encoding())


# Псевдографика → ASCII. Блока заливки на таком терминале нет — рисуем
# «#», как на DOS-терминалах; черты и углы — «-», «|», «+».
BOX = {
    "─": "-", "━": "-", "│": "|", "┃": "|",
    "┌": "+", "┐": "+", "└": "+", "┘": "+",
    "├": "+", "┤": "+", "┬": "+", "┴": "+", "┼": "+",
    "═": "=", "║": "|", "╔": "+", "╗": "+", "╚": "+", "╝": "+",
    "╠": "+", "╣": "+", "╦": "+", "╩": "+", "╬": "+",
    "█": "#", "▓": "#", "▒": ":", "░": ".",
    "▀": "#", "▄": "#", "▌": "#", "▐": "#",
    "■": "*", "□": "*", "▲": "*", "▼": "*", "►": "*", "◄": "*",
    # стрелки в легенде подвала: на «жёстком» терминале знака стрелки нет,
    # показываем общепринятые иероглифы терминала (Carlson, SMACS)
    "↑": "^", "↓": "v", "→": ">", "←": "<", "↔": "<>",
    "№": "N", "…": "...", "—": "-", "–": "-", "−": "-",
    "«": '"', "»": '"', "„": '"', "“": '"', "”": '"',
    "‘": "'", "’": "'", "·": ".", "•": "*", "°": "o",
    "§": "S", "±": "+/-", "×": "x", "÷": "/",
}

_UPPER = {
    "А": "A", "Б": "B", "В": "V", "Г": "G", "Д": "D", "Е": "E",
    "Ё": "Yo", "Ж": "Zh", "З": "Z", "И": "I", "Й": "Y", "К": "K",
    "Л": "L", "М": "M", "Н": "N", "О": "O", "П": "P", "Р": "R",
    "С": "S", "Т": "T", "У": "U", "Ф": "F", "Х": "Kh", "Ц": "Ts",
    "Ч": "Ch", "Ш": "Sh", "Щ": "Shch", "Ъ": '"', "Ы": "Y",
    "Ь": "'", "Э": "E", "Ю": "Yu", "Я": "Ya",
    # украинские/белорусские — чтобы «жёсткий» терминал не спотыкался
    "І": "I", "Ї": "Yi", "Є": "Ye", "Ґ": "G", "Ў": "U",
}
_LOWER = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e",
    "ё": "yo", "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k",
    "л": "l", "м": "m", "н": "n", "о": "o", "п": "p", "р": "r",
    "с": "s", "т": "t", "у": "u", "ф": "f", "х": "kh", "ц": "ts",
    "ч": "ch", "ш": "sh", "щ": "shch", "ъ": '"', "ы": "y",
    "ь": "'", "э": "e", "ю": "yu", "я": "ya",
    "і": "i", "ї": "yi", "є": "ye", "ґ": "g", "ў": "u",
}

TABLE = {**BOX, **_UPPER, **_LOWER}


class Output:
    """Печать в терминал с подстраховкой от «жёсткого» stdout.

    Обычный терминал — просто пишем. На «жёстком» каждый знак, который
    кодировка не берёт, заменяется на ближайший печатный (кириллица →
    латиница, псевдографика → ASCII). Решение кэшируется по знаку, так
    что после первого кадра стоимость — словарь, а не перебор кодировок.

    Управляющие последовательности (ESC …) всегда ASCII: их кладут в
    `raw` мимо подстраховки — иначе смазались бы и границы кадра.
    """

    def __init__(self, encoding: str | None = None, force: bool = False) -> None:
        self.encoding = console_encoding() if encoding is None else encoding
        self.ascii = bool(force) or not _can_encode(PROBE, self.encoding)
        self._sub: dict[str, str] = {}

    def _repl(self, ch: str) -> str:
        """Во что превращается не-ASCII знак (результат кэшируется)."""
        got = self._sub.get(ch)
        if got is None:
            try:
                ch.encode(self.encoding)
            except (UnicodeEncodeError, LookupError):
                got = TABLE.get(ch, "?")
            else:
                got = ch                 # этот знак терминал берёт как есть
            self._sub[ch] = got
        return got

    def adapt(self, text: str) -> str:
        """Текст → то, что терминал способен показать."""
        if not self.ascii or text.isascii():
            return text
        return "".join(c if c.isascii() else self._repl(c) for c in text)

    def write(self, text: str) -> None:
        sys.stdout.write(self.adapt(text))

    def writeln(self, text: str = "") -> None:
        self.write(text + "\n")

    def flush(self) -> None:
        sys.stdout.flush()