"""Эмулятор терминала «Электроника 15ИЭ-00-013» (Фрязинский дисплей).

Экран: 80×25 кадровых строк (служебная панель — под кадром),
знакогенератор 7×8 из ПЗУ КР556РТ5 (rom/chargen-15ie.bin),
клавиатура 15ВВВ-97-006.

Версия (semver, единый источник — здесь; показывается в --version,
строке состояния над кадром и при запуске):
  0.4.0  удержание экрана (Ctrl+L): выдача ЭВМ останавливается — экран
         замирает, эмулятор линию не читает, машина упирается в буфер
         (защита от зациклившихся программ, «заливающих» экран); в линию
         уходит команда 15ИЭ «Сброс» (0x0C) — на линии, объявленной ОС
         терминалом «Э» (НУС N 1), ДИСПАК по ней отменяет идущую выдачу;
         Ctrl+Q снимает удержание и возвращает окно к живой выдаче;
         окно само следует за выдачей и после листания вниз (раньше
         закреплённое окно отставало от текста на строку, курсор уходил
         под нижнюю кромку и экран приходилось опускать вручную);
         «пробел поддержки» отправляется только в АВТОНОМНО — в С ЭВМ он
         вклинивался в выдачу и сбивал её; счётчик «БУФЕР=» в подвале при
         удержании не прячется (в удержании можно работать автономно)
  0.3.0  контроль состояния SSH-моста: раз в минуту терминал спрашивает
         у линии (моста) состояние и подвал честно показывает «ЛИНИЯ=НЕТ»,
         если связь пропала «молча» (соединение не рвётся, а данных нет);
         мост отвечает на «status» (сессии и линии) и печатает сводку о
         себе в журнал; «ЛИНИЯ=» в подвале показывает тип канала
         (КВУ/ДКС) вместо кодировки, а состояние линии — только в подвале
         (из строки состояния над кадром тип убран); мост больше не рвёт
         SSH-соединение, когда запрошенная линия занята (терминал берёт
         следующую), и переживает тишину в линии (раньше сессия умирала
         через две секунды молчания); обрыв SSH-транспорта (EOFError) не
         роняет эмулятор трейсбеком
  0.2.7  переход С ЭВМ → АВТОНОМНО (F9) добавляет текст кадра в буфер
         набора: набор продолжает текст экрана, ПЕРЕДАЧА отдаёт и его,
         Ctrl+U отменяет перенос; строки ЭВМ больше не пропадают при
         наборе буфера больше экрана (кадр — окно на буфер, всё в
         буфере); строка кадра длиной, кратной 80 знакам, при
         перерисовке больше не даёт пустого интервала после себя
         (перенос печати уже перевёл строку — ПР без ПС); строки
         вставки длиннее кадра ломаются по пробелам — слова не
         разделяются (слово длиннее ряда рвётся по краю кадра);
         большой текст приходит кусками-чтениями: незакрытый хвост
         ждёт продолжения и отдаётся по паузе или следующей клавише,
         слова на стыках кусков не рвутся; движения курсора (стрелки,
         Home/End, листание) — не шаг отмены: набор до и после
         движения откатывается одним Ctrl+U;
         закреплённый просмотр истории (PgUp) снимается
         переходом и набором — раньше набор шёл «вслепую»
  0.2.6  вставка из буфера обмена ОС без потерь и без мусора: OSC52
         (Ctrl+Shift+C — выделенное в буфер ОС, Ctrl+Shift+V — запрос
         вставки), bracketed paste (ESC[200~…ESC[201~) одним ключом,
         взрыв знаков одного чтения тоже считается вставкой; ввод
         больше не теряется (проба CSI-u, сброс ввода на старте,
         залповое чтение — вставка идёт в разы быстрее); эхо набора
         в АВТОНОМНО спускается под вывод ЭВМ; F3: без выделения —
         очистка буфера без правки экрана (отменяется Ctrl+U)
  0.2.5  unicode-вывод оболочки SIMH на raw-линии и автопереключение
         на Н0 по приглашению «set>»; выпадающая строка сообщения ЭВМ
         под состоянием (гасится первой клавишей); листание страниц
         набора PgUp/PgDn и колесом в АВТОНОМНО; ВЕРСИЯ в строке
         состояния больше не жертвуется подрезкой
  0.2.4  курсор автономного набора при буфере больше одного экрана
         (знак встаёт ровно под курсором, строки не съезжают),
         подсказка «СПРАВКА=F12» — в правый угол строки состояния,
         справка подвала скрыта по умолчанию (включается --show-help)
  0.2.3  справка подвала переключается в ходе сеанса (F12; F1 занят ОС),
         Shift+Home/End заблокированы (выделение строки — Ctrl+Home/End),
         откат Ctrl+U по слову, «пробел поддержки» раз в минуту,
         сообщение ЭВМ в АВТОНОМНО — индикатор «ОТ ЭВМ», а не кадр
  0.2.2  сеанс по умолчанию идёт до Ctrl-C (раньше прямой запуск сам
         закрывался через 30 с — «линия обрывается постоянно»),
         --keylog для диагностики клавиш, полный разбор CSI-u
  0.2.1  F5 в АВТОНОМНО удаляет видимую страницу из буфера набора,
         Shift+Home/End выделяют и в режиме С ЭВМ (по кадру)
  0.2.0  локальные стрелки и выделение Shift+Home/End в АВТОНОМНО,
         удаление страницы по F5, keep-alive линии, живучесть при
         обрыве SSH (ЛИНИЯ=НЕТ), исправлен эх-обмен stdio://
  0.1.0  первая рабочая версия
"""
