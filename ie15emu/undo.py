"""Отмена правок буфера набора в режиме АВТОНОМНО.

Буфер набора — то, что оператор набирает, ещё не отданное линии
(АВТОНОМНО). Ошибиться легко: набрал лишнее, стёр не то, и блок ушёл бы
в ЭВМ с мусором. Отмена возвращает буфер к состоянию «N нажатий назад».

Храним не операции, а снимки буфера перед каждым изменением: правки
буфера идут из разных мест (клавиши, ВЗЯТЬ выделения, вставка), и набор
операций на каждую пришлось бы заводить отдельно. Буфер набора короткий
(одна-две строки), поэтому снимок стоит дешевле, чем разбор истории
команд.

Глубина задаётся конфигом `[terminal] undo` (по умолчанию 20 шагов);
0 — отмена выключена (снимки не хранятся, память не тратится).
"""

from __future__ import annotations

DEFAULT_UNDO = 20       # шагов отмены по умолчанию


class UndoStack:
    """Снимки буфера набора: ограниченная глубина, отмена к предыдущему.

    Один шаг — одна отмена: снимок кладётся ПЕРЕД изменением буфера, так
    что `undo()` возвращает состояние до последней правки.
    """

    def __init__(self, depth: int = DEFAULT_UNDO) -> None:
        self.depth = max(0, int(depth))
        self._items: list[bytes] = []

    def __len__(self) -> int:
        return len(self._items)

    @property
    def available(self) -> bool:
        """Есть ли что отменять."""
        return bool(self._items)

    def snapshot(self, buffer: bytearray | bytes) -> None:
        """Запомнить состояние буфера перед правкой.

        Последний снимок подменяем, а не добавляем: подряд идущие правки
        без отмены между ними (обычный набор текста) не должны съедать
        глубину — иначе двадцать набранных знаков «съедали» бы всю
        историю отмены. Снимок меняется только когда буфер отличается от
        последнего запомненного.
        """
        if self.depth <= 0:
            return
        data = bytes(buffer)
        if self._items and self._items[-1] == data:
            return                  # буфер не менялся — шаг не тратим
        self._items.append(data)
        # переполнение: глубина шагов уходит на самые старые правки
        while len(self._items) > self.depth:
            self._items.pop(0)

    def undo(self, buffer: bytearray) -> bool:
        """Вернуть буферу состояние до последней правки.

        True — отмена выполнена, False — отменять нечего (пусто).
        """
        if not self._items:
            return False
        data = self._items.pop()
        buffer[:] = data
        return True

    def clear(self) -> None:
        """Сбросить историю (отдача буфера, смена режима, очистка)."""
        self._items.clear()