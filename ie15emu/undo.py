"""Отмена правок буфера набора в режиме АВТОНОМНО.

Буфер набора — то, что оператор набирает, ещё не отданное линии
(АВТОНОМНО). Ошибиться легко: набрал лишнее, стёр не то, и блок ушёл бы
в ЭВМ с мусором. Отмена возвращает буфер к состоянию «N шагов назад».

Шаг откала — СЛОВО, а не знак: Ctrl+U убирает целиком последнее набранное
слово (а не одну букву). Границу шага помечает `step()`:
  * разделители — пробел, точка, ПР (конец слова/строки);
  * не-знаковые клавиши — Enter, ВК, навигация, F-клавиши (см. feed_key);
  * завершение дискретных правок — взятое выделение, очистка страницы.
Пока шаг открыт, `snapshot()` снимок не кладёт: прежний снимок (до начала
слова) и есть цель отката.

Храним не операции, а снимки буфера перед правками: правки идут из разных
мест (клавиши, ВЗЯТЬ выделения, вставка), и набор операций на каждую
пришлось бы заводить отдельно. Буфер набора короткий, поэтому снимок
стоит дешевле, чем разбор истории команд.

Глубина задаётся конфигом `[terminal] undo` (по умолчанию 20 шагов —
это 20 слов/действий); 0 — отмена выключена (снимки не хранятся).
"""

from __future__ import annotations

DEFAULT_UNDO = 20       # шагов отмены по умолчанию


class UndoStack:
    """Снимки буфера набора: откат по шагам (слово/действие).

    Один вызов `undo()` возвращает состояние до последнего шага. Шаг
    открывается либо первым снимком, либо после `step()` — границы шага
    ставит вызывающий (см. докстринг модуля).
    """

    def __init__(self, depth: int = DEFAULT_UNDO) -> None:
        self.depth = max(0, int(depth))
        self._items: list[bytes] = []
        self._new_step = True    # следующий снимок откроет новый шаг

    def __len__(self) -> int:
        return len(self._items)

    @property
    def available(self) -> bool:
        """Есть ли что отменять."""
        return bool(self._items)

    def step(self) -> None:
        """Пометить границу шага отмены.

        Следующая правка начнёт новый шаг: её снимок ляжет в стек,
        и Ctrl+U вернёт буфер именно к этому состоянию. Вызывается на
        разделителях, при навигации и после дискретных правок.
        """
        self._new_step = True

    def snapshot(self, buffer: bytearray | bytes) -> None:
        """Запомнить состояние буфера перед правкой.

        Пока шаг открыт (`step()` не звали), снимок не добавляется:
        в стеке лежит состояние до начала слова — откат идёт по слову,
        а не по знаку, и глубина отмены тратится на слова, а не на
        буквы. Пустая запись (буфер не менялся) шаг тоже не открывает.
        """
        if self.depth <= 0:
            return
        if not self._new_step:
            return                      # шаг уже открыт — цель отката лежит
        data = bytes(buffer)
        if self._items and self._items[-1] == data:
            return                      # состояние не менялось — не кладём
        self._items.append(data)
        self._new_step = False
        # переполнение: глубина шагов уходит на самые старые правки
        while len(self._items) > self.depth:
            self._items.pop(0)

    def undo(self, buffer: bytearray) -> bool:
        """Вернуть буферу состояние до последнего шага.

        True — отмена выполнена, False — отменять нечего (пусто).
        """
        if not self._items:
            return False
        data = self._items.pop()
        buffer[:] = data
        self._new_step = True           # следующая правка — новый шаг
        return True

    def clear(self) -> None:
        """Сбросить историю (отдача буфера, смена режима, очистка)."""
        self._items.clear()
        self._new_step = True
